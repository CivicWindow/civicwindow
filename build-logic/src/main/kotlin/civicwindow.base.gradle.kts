// Enforcement: the build fails on any Kotlin compiler warning and on a resolved dependency that
// differs from its lock file; review is the check until the static-analysis, testing and coverage
// plugins are added.
// Documentation: Gradle, "Dependency locking" and "Toolchains for JVM projects"; Kotlin Gradle
// plugin, "Gradle compiler options" (allWarningsAsErrors) and "Gradle Java toolchains support".
//
// The base rules every project applies. The JDK comes from the catalog, never from a literal.

import org.gradle.api.artifacts.VersionCatalogsExtension
import org.jetbrains.kotlin.gradle.dsl.KotlinBaseExtension
import org.jetbrains.kotlin.gradle.tasks.KotlinCompilationTask

val libs = extensions.getByType<VersionCatalogsExtension>().named("libs")
val jdk = libs.findVersion("jdk").get().requiredVersion.toInt()

// Every configuration is locked. The lock files are generated by Gradle with the write-locks
// option, never written by hand.
dependencyLocking {
    lockAllConfigurations()
}

// Kotlin compiler warnings fail the build in every project that compiles Kotlin.
tasks.withType<KotlinCompilationTask<*>>().configureEach {
    compilerOptions.allWarningsAsErrors.set(true)
}

// JDK toolchain: the catalog's JDK for Kotlin JVM, Android library and Android application
// projects.
// open: the extension type used here (KotlinBaseExtension) and the timing of its registration under
// the Android plugins' built-in Kotlin are checked again at the first build.
listOf(
    "org.jetbrains.kotlin.jvm",
    "com.android.library",
    "com.android.application"
).forEach { pluginId ->
    pluginManager.withPlugin(pluginId) {
        extensions.configure<KotlinBaseExtension>("kotlin") {
            jvmToolchain(jdk)
        }
    }
}

